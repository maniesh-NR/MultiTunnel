#!/bin/sh
# mingw-zig-shims.sh — zig cc/cxx/ar wrappers that translate the Rust
# triple (x86_64-pc-windows-gnu) into zig's triple (x86_64-windows-gnu).
#
# WHY: `cargo clippy --target x86_64-pc-windows-gnu` runs build scripts
# (ring, via reqwest+rustls) that need a cross C compiler. There is no
# mingw toolchain in the sandbox/CI, but zig cc is one. cargo-zigbuild
# does this translation internally for builds; these shims bring plain
# `cargo clippy --target` to parity.
#
# Usage:
#   sh scripts/mingw-zig-shims.sh [output-dir]     # default /tmp/mt-zig-shims
# Then:
#   export CC_x86_64_pc_windows_gnu=<dir>/zig-cc
#   export CXX_x86_64_pc_windows_gnu=<dir>/zig-cxx
#   export AR_x86_64_pc_windows_gnu=<dir>/zig-ar
#   cargo clippy --workspace --all-targets --target x86_64-pc-windows-gnu -- -D warnings
#
# Zig selection: $ZIG env if set (e.g. "python3 -m ziglang"), else `zig`
# on PATH, else the pip wheel via `python3 -m ziglang`.
set -eu

out="${1:-/tmp/mt-zig-shims}"
if [ -n "${ZIG:-}" ]; then
  zigcmd="$ZIG"
elif command -v zig >/dev/null 2>&1; then
  zigcmd="zig"
elif python3 -m ziglang version >/dev/null 2>&1; then
  zigcmd="python3 -m ziglang"
else
  echo "error: no zig found (set ZIG=..., install zig, or pip install ziglang)" >&2
  exit 1
fi

mkdir -p "$out"

for tool in cc cxx; do
  cat >"$out/zig-$tool" <<EOF
#!/bin/sh
# Generated by scripts/mingw-zig-shims.sh — do not edit.
n=\$#
for a in "\$@"; do
  case "\$a" in
    x86_64-pc-windows-gnu) set -- "\$@" x86_64-windows-gnu ;;
    --target=x86_64-pc-windows-gnu) set -- "\$@" --target=x86_64-windows-gnu ;;
    -target=x86_64-pc-windows-gnu) set -- "\$@" -target=x86_64-windows-gnu ;;
    *) set -- "\$@" "\$a" ;;
  esac
done
shift "\$n"
exec $zigcmd $tool "\$@"
EOF
  chmod +x "$out/zig-$tool"
done

cat >"$out/zig-ar" <<EOF
#!/bin/sh
exec $zigcmd ar "\$@"
EOF
chmod +x "$out/zig-ar"

echo "shims in $out (zig: $zigcmd)"
echo "export CC_x86_64_pc_windows_gnu=$out/zig-cc"
echo "export CXX_x86_64_pc_windows_gnu=$out/zig-cxx"
echo "export AR_x86_64_pc_windows_gnu=$out/zig-ar"

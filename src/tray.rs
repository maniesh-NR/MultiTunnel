// ---- pure helpers (host-testable, cfg'd like sysproxy/elevate) --------------

/// Human word for a lifecycle state (menus/tooltips).
#[cfg(any(windows, test))]
fn state_word(s: State) -> &'static str {
    match s {
        State::Disconnected => "Disconnected",
        State::Connecting => "Connecting",
        State::Connected => "Connected",
        State::Failed => "Failed",
    }
}

/// First menu row: the current state, e.g. `State: Connected`.
#[cfg(any(windows, test))]
fn state_line(snap: &Snapshot) -> String {
    format!("State: {}", state_word(snap.state))
}

/// Links row: `Links: N (merging)` while bonded; `Links: bonding off` when
/// net-merge is disabled in the config; `Links: unavailable` when enabled
/// but not merging (disconnected, or bonding not up yet).
#[cfg(any(windows, test))]
fn links_line(snap: &Snapshot, net_merge_enabled: bool) -> String {
    if !net_merge_enabled {
        "Links: bonding off".to_string()
    } else if snap.merging {
        format!("Links: {} (merging)", snap.links.len())
    } else {
        "Links: unavailable".to_string()
    }
}

/// Reduce an error message to its first line, capped at `cap` chars with an
/// ellipsis. Errors from the supervisor can be multi-line; tooltips and the
/// menu want one short line.
#[cfg(any(windows, test))]
fn snippet(s: &str, cap: usize) -> String {
    let first = s.lines().next().unwrap_or("").trim();
    if first.chars().count() < cap {
        first.to_string()
    } else {
        let cut: String = first.chars().take(cap - 1).collect();
        cut + "…"
    }
}

/// Tooltip text: state line plus first-line snippets of the top-level,
/// bond and probe errors (blank errors are omitted). The result is capped
/// to the NIF_TIP limit later by [`tip_array`].
#[cfg(any(windows, test))]
fn tooltip_text(snap: &Snapshot) -> String {
    let mut lines = vec![format!("MultiTunnel — {}", state_word(snap.state))];
    for (tag, err) in [
        ("error", &snap.error),
        ("bond", &snap.bond_error),
        ("probe", &snap.probe_error),
    ] {
        if let Some(e) = err {
            if !e.trim().is_empty() {
                lines.push(format!("{tag}: {}", snippet(e, 48)));
            }
        }
    }
    lines.join("\n")
}

/// Copy `s` into a NIF_TIP-shaped, NUL-terminated `[u16; 128]` buffer: at
/// most 127 UTF-16 code units + terminator, and never a surrogate pair
/// split across units 126/127 (a dangling high surrogate would corrupt the
/// shell's decode and could eat the terminator slot).
#[cfg(any(windows, test))]
fn tip_array(s: &str) -> [u16; 128] {
    let mut out = [0u16; 128];
    for (i, unit) in s.encode_utf16().enumerate() {
        if i >= 127 {
            break; // slot 127 is reserved for the NUL terminator
        }
        if i == 126 && (0xD800..0xDC00).contains(&unit) {
            break; // high surrogate at the last slot: its pair would not fit
        }
        out[i] = unit;
    }
    out
}

// ---- ICO byte parsing -------------------------------------------------------

/// One ICONDIRENTRY: the image's declared square size and where its RT_ICON
/// bytes live inside the file.
#[cfg(any(windows, test))]
struct IcoEntry {
    dim: u32,
    offset: u32,
    len: u32,
}

/// Parse the 6-byte ICONDIR + 16-byte entries. `None` when the bytes are not
/// a well-formed icon directory (bad magic/type, truncated directory).
#[cfg(any(windows, test))]
fn ico_entries(ico: &[u8]) -> Option<Vec<IcoEntry>> {
    if ico.len() < 6 {
        return None;
    }
    let reserved = u16::from_le_bytes([ico[0], ico[1]]);
    let kind = u16::from_le_bytes([ico[2], ico[3]]);
    let count = u16::from_le_bytes([ico[4], ico[5]]);
    if reserved != 0 || kind != 1 {
        return None; // 1 = icon (2 would be a cursor file)
    }
    let mut out = Vec::with_capacity(count as usize);
    for i in 0..count as usize {
        let start = 6 + i * 16;
        let end = start.checked_add(16)?;
        if end > ico.len() {
            return None;
        }
        let e = &ico[start..end];
        // Width/height 0 in the directory mean 256 pixels.
        let dim = match e[0] {
            0 => 256,
            w => w as u32,
        };
        let len = u32::from_le_bytes([e[8], e[9], e[10], e[11]]);
        let offset = u32::from_le_bytes([e[12], e[13], e[14], e[15]]);
        out.push(IcoEntry { dim, offset, len });
    }
    Some(out)
}

/// Extract the RT_ICON image bytes for a `preferred` square size.
///
/// `CreateIconFromResourceEx` wants the image bytes a directory entry points
/// at — NOT the ICO directory itself (the 6-byte header + 16-byte entries are
/// bookkeeping that the function does not understand; the entry payload is
/// the RT_ICON resource: BITMAPINFOHEADER with doubled height + XOR + AND
/// masks, or a PNG). Selection: exact square match first, then the largest
/// entry that fits, then the largest overall; empty/out-of-bounds slices are
/// rejected.
#[cfg(any(windows, test))]
fn ico_image_bytes(ico: &[u8], preferred: u32) -> Option<&[u8]> {
    let entries = ico_entries(ico)?;
    let pick = entries
        .iter()
        .find(|e| e.dim == preferred)
        .or_else(|| {
            entries
                .iter()
                .filter(|e| e.dim <= preferred)
                .max_by_key(|e| e.dim)
        })
        .or_else(|| entries.iter().max_by_key(|e| e.dim))?;
    if pick.len == 0 {
        return None;
    }
    let start = pick.offset as usize;
    let end = start.checked_add(pick.len as usize)?;
    ico.get(start..end)
}

// ---- raw-status dump --------------------------------------------------------

/// Path of the "Show raw status" dump inside the state dir.
#[cfg(any(windows, test))]
fn status_dump_path(state_dir: &std::path::Path) -> std::path::PathBuf {
    state_dir.join("net-merge-status.txt")
}

/// Content of the raw-status dump: the pretty-printed supervisor snapshot
/// plus the raw net-merge status text (placeholder when nothing was polled
/// yet). Deterministic (no timestamp) so it stays unit-testable.
#[cfg(any(windows, test))]
fn status_dump(snap: &Snapshot) -> String {
    let mut out = String::from(
        "MultiTunnel — supervisor snapshot + raw net-merge status\n\n== supervisor snapshot ==\n",
    );
    match serde_json::to_string_pretty(snap) {
        Ok(json) => {
            out.push_str(&json);
            out.push('\n');
        }
        Err(e) => out.push_str(&format!("(snapshot serialization failed: {e})\n")),
    }
    out.push_str("\n== raw net-merge status ==\n");
    if snap.raw_status.trim().is_empty() {
        out.push_str("(no status yet — poll pending or net-merge unreachable)\n");
    } else {
        out.push_str(snap.raw_status.trim_end());
        out.push('\n');
    }
    out
}

/// Write the raw-status dump (creating the state dir if needed).
#[cfg(any(windows, test))]
fn write_status_dump(path: &std::path::Path, snap: &Snapshot) -> crate::error::Result<()> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir)?;
    }
    std::fs::write(path, status_dump(snap))?;
    Ok(())
}


/// Selectable commands (menu item ids map 1:1 through [`cmd_from_id`]).
#[cfg(any(windows, test))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Cmd {
    Connect,
    Disconnect,
    ShowRawStatus,
    OpenLogFolder,
    EditConfig,
    Exit,
}

/// One row of the tray menu — a pure plan the FFI glue renders.
#[cfg(any(windows, test))]
#[derive(Debug, Clone, PartialEq, Eq)]
enum MenuEntry {
    Separator,
    /// Grayed, non-selectable informational row.
    Info(String),
    /// Selectable action; `enabled == false` renders grayed.
    Item {
        label: String,
        cmd: Cmd,
        enabled: bool,
    },
}

/// Connect is offered while down or failed (a retry from Failed is a full
/// sequence per the supervisor contract).
#[cfg(any(windows, test))]
fn connect_enabled(state: State) -> bool {
    matches!(state, State::Disconnected | State::Failed)
}

/// Disconnect is offered while a cycle is live; it also cancels a pending
/// connect (supervisor serializes via its op_lock).
#[cfg(any(windows, test))]
fn disconnect_enabled(state: State) -> bool {
    matches!(state, State::Connecting | State::Connected)
}

/// The full menu, rebuilt FRESH from the snapshot at every open:
/// state line / Connect / Disconnect / links line / raw status / logs /
/// config / Exit, with separators between the groups.
#[cfg(any(windows, test))]
fn menu_plan(snap: &Snapshot, net_merge_enabled: bool) -> Vec<MenuEntry> {
    vec![
        MenuEntry::Info(state_line(snap)),
        MenuEntry::Separator,
        MenuEntry::Item {
            label: "Connect".into(),
            cmd: Cmd::Connect,
            enabled: connect_enabled(snap.state),
        },
        MenuEntry::Item {
            label: "Disconnect".into(),
            cmd: Cmd::Disconnect,
            enabled: disconnect_enabled(snap.state),
        },
        MenuEntry::Separator,
        MenuEntry::Info(links_line(snap, net_merge_enabled)),
        MenuEntry::Item {
            label: "Show raw status".into(),
            cmd: Cmd::ShowRawStatus,
            enabled: true,
        },
        MenuEntry::Item {
            label: "Open log folder".into(),
            cmd: Cmd::OpenLogFolder,
            enabled: true,
        },
        MenuEntry::Item {
            label: "Edit config".into(),
            cmd: Cmd::EditConfig,
            enabled: true,
        },
        MenuEntry::Separator,
        MenuEntry::Item {
            label: "Exit".into(),
            cmd: Cmd::Exit,
            enabled: true,
        },
    ]
}

/// Menu item id for a command (WM_COMMAND delivers it in LOWORD(wParam)).
#[cfg(any(windows, test))]
const fn id_for_cmd(cmd: Cmd) -> usize {
    match cmd {
        Cmd::Connect => 1001,
        Cmd::Disconnect => 1002,
        Cmd::ShowRawStatus => 1003,
        Cmd::OpenLogFolder => 1004,
        Cmd::EditConfig => 1005,
        Cmd::Exit => 1006,
    }
}

/// Inverse of [`id_for_cmd`] for the WM_COMMAND handler.
#[cfg(any(windows, test))]
const fn cmd_from_id(id: usize) -> Option<Cmd> {
    match id {
        1001 => Some(Cmd::Connect),
        1002 => Some(Cmd::Disconnect),
        1003 => Some(Cmd::ShowRawStatus),
        1004 => Some(Cmd::OpenLogFolder),
        1005 => Some(Cmd::EditConfig),
        1006 => Some(Cmd::Exit),
        _ => None,
    }
}


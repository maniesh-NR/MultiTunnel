//! Windows notification-area (tray) UI (stage S3 — implementer agent S3).
//!
//! CONTRACT (stage plan; DECISIONS.md D4 — raw Win32 via windows-sys, NOT
//! the tray-icon crate):
//! - `run(Arc<Supervisor>, config_path)` — installs a tray icon, runs the
//!   Win32 message loop until the user picks Exit, returns `Ok(())` after
//!   clean teardown. Must be called exactly once, from the thread that
//!   owns the window (the binary's main thread). Non-Windows stub: `Err`.
//! - Message-only window built from the predefined `"STATIC"` system class
//!   (no `RegisterClass`) with `HWND_MESSAGE` as parent, subclassed via
//!   `SetWindowLongPtrW(GWLP_WNDPROC)`; unhandled messages fall through to
//!   `DefWindowProcW`.
//! - Tray icon via `Shell_NotifyIconW` (NIF_MESSAGE + NIF_ICON + NIF_TIP),
//!   popup menu rebuilt FRESH from the supervisor [`Snapshot`] at every
//!   open, tooltip refreshed by a 1 s `WM_TIMER` (only when the text
//!   changed), clean `NIM_DELETE` teardown.
//! - Supervisor ops (`connect`/`disconnect` hold an op_lock and can block
//!   up to ~15 s) ALWAYS run on worker threads — never inside the window
//!   procedure, which must keep pumping messages.
//! - Embedded icon: `include_bytes!("../assets/icon.ico")` parsed at
//!   runtime by [`ico_image_bytes`] (ICO directory → RT_ICON entry bytes)
//!   and handed to `CreateIconFromResourceEx`; the standard application
//!   icon is the fallback if that fails.
//!
//! Unsafe-FFI review protocol (D6): every `unsafe` block below is small and
//! carries a `SAFETY:` comment; all logic that can be pure lives in the
//! host-testable helpers (pattern of sysproxy.rs/elevate.rs) and is unit
//! tested on the Linux host. Handler state travels through a thread-local
//! `&'static TrayCtx` — the window procedure only ever runs on the thread
//! that created the window, and no borrow guard is held across any FFI
//! call that pumps messages (`TrackPopupMenuEx` re-enters the procedure
//! through its modal loop).

#[cfg(any(windows, test))]
use crate::supervisor::{Snapshot, State};


    /// Minimal synthetic ICO: entries of the given square dims, each with a
    /// recognizable `dim*4`-byte payload, laid out like a real file.
    fn synthetic_ico(dims: &[u32]) -> Vec<u8> {
        let mut v = vec![0, 0, 1, 0]; // reserved=0, type=icon
        v.extend_from_slice(&(dims.len() as u16).to_le_bytes());
        let mut off = (6 + 16 * dims.len()) as u32;
        for &d in dims {
            v.push(if d == 256 { 0 } else { d as u8 });
            v.push(if d == 256 { 0 } else { d as u8 });
            v.push(0);
            v.push(0);
            v.extend_from_slice(&1u16.to_le_bytes()); // planes
            v.extend_from_slice(&32u16.to_le_bytes()); // bit count
            v.extend_from_slice(&(d * 4).to_le_bytes()); // bytes in res
            v.extend_from_slice(&off.to_le_bytes()); // image offset
            off += d * 4;
        }
        v.resize(off as usize, 0xAB); // payload filler
        v
    }


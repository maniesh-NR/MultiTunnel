#[cfg(windows)]
mod win {
    use std::cell::RefCell;
    use std::path::{Path, PathBuf};
    use std::sync::Arc;
    use std::thread;
    use std::time::Duration;

    use windows_sys::Win32::Foundation::{HWND, LPARAM, LRESULT, POINT, WPARAM};
    use windows_sys::Win32::UI::Shell::{
        Shell_NotifyIconW, NIF_ICON, NIF_MESSAGE, NIF_TIP, NIM_ADD, NIM_DELETE, NIM_MODIFY,
        NOTIFYICONDATAW,
    };
    use windows_sys::Win32::UI::WindowsAndMessaging::{
        AppendMenuW, CreateIconFromResourceEx, CreatePopupMenu, CreateWindowExW, DefWindowProcW,
        DestroyIcon, DestroyMenu, DestroyWindow, DispatchMessageW, GetCursorPos, GetMessageW,
        KillTimer, LoadIconW, PostMessageW, PostQuitMessage, SetForegroundWindow, SetTimer,
        SetWindowLongPtrW, TrackPopupMenuEx, TranslateMessage, GWLP_WNDPROC, HICON, HMENU,
        HWND_MESSAGE, IDI_APPLICATION, LR_DEFAULTCOLOR, MF_GRAYED, MF_SEPARATOR, MF_STRING, MSG,
        TPM_BOTTOMALIGN, TPM_RIGHTBUTTON, WM_APP, WM_COMMAND, WM_DESTROY, WM_LBUTTONUP, WM_NULL,
        WM_RBUTTONUP, WM_TIMER,
    };

    use super::{
        cmd_from_id, ico_image_bytes, id_for_cmd, menu_plan, status_dump_path, tip_array,
        tooltip_text, write_status_dump, Cmd, MenuEntry, ICON_BYTES,
    };
    use crate::elevate::to_wide;
    use crate::supervisor::Supervisor;

    /// Tray icon id (NOTIFYICONDATAW.uID) — one icon per window.
    const TRAY_ID: u32 = 1;
    /// Callback message the shell sends to our window for icon events.
    const TRAY_CALLBACK: u32 = WM_APP + 1;
    /// Tooltip refresh timer id + period.
    const TIMER_ID: usize = 1;
    const TIP_PERIOD_MS: u32 = 1000;
    /// Preferred icon edge (the embedded ICO's primary entry; the shell
    /// scales it to the small-icon slot as needed).
    const ICON_SIZE: u32 = 32;
    /// Upper bound on how long Exit waits for the best-effort disconnect
    /// worker (the supervisor op_lock can block ~15 s; we never do).
    const EXIT_WAIT: Duration = Duration::from_secs(2);

    /// Window/thread state. `ui` is only ever touched from the message-loop
    /// thread, so a `RefCell` is enough (no lock contention with workers).
    struct TrayCtx {
        supervisor: Arc<Supervisor>,
        config_path: PathBuf,
        ui: RefCell<UiState>,
    }

    struct UiState {
        hwnd: HWND,
        /// Current tray HICON; null only before `run` installs one.
        icon: HICON,
        /// True only when `icon` came from `CreateIconFromResourceEx` (it
        /// must then be `DestroyIcon`d). A `LoadIconW` fallback is a SHARED
        /// system icon and must never be destroyed.
        icon_owned: bool,
        /// False after NIM_DELETE (Exit deletes the icon before quitting).
        icon_added: bool,
        /// Last tooltip pushed to the shell (skips redundant NIM_MODIFY).
        last_tip: String,
    }

    thread_local! {
        /// The tray context for THIS thread: `run` installs it before the
        /// window exists and the window procedure only ever runs on that
        /// thread, so handlers may re-enter (the `TrackPopupMenuEx` modal
        /// loop dispatches messages) as long as no borrow guard is held
        /// across a message-pumping call — handlers copy the `&'static`
        /// reference out and drop the guard immediately.
        static CTX: RefCell<Option<&'static TrayCtx>> = const { RefCell::new(None) };
    }

    /// Copy of the context reference out of the thread-local (the Option
    /// of references is `Copy`; the borrow guard is dropped before returning,
    /// so re-entrant calls during modal loops are safe).
    fn ctx() -> Option<&'static TrayCtx> {
        CTX.with(|c| *c.borrow())
    }

    /// Best-effort diagnostic for workers/handlers. The GUI subsystem
    /// usually has no stderr; failed writes are ignored — never `eprintln!`,
    /// which panics when the handle is invalid (S2-REV-B P2-5).
    fn log_err(op: &str, e: &crate::Error) {
        use std::io::Write as _;
        let _ = writeln!(std::io::stderr(), "multitunnel-tray: {op} failed: {e}");
    }

    // ---- entry point ---------------------------------------------------------

    /// Install the tray icon and run the message loop until Exit. See the
    /// module docs; called once from the binary's main thread.
    pub fn run(supervisor: Arc<Supervisor>, config_path: PathBuf) -> crate::error::Result<()> {
        // Leak the context: it must live as long as the (static) window
        // procedure can be called, i.e. for the whole process lifetime.
        let ctx: &'static TrayCtx = Box::leak(Box::new(TrayCtx {
            supervisor,
            config_path,
            ui: RefCell::new(UiState {
                hwnd: std::ptr::null_mut(),
                icon: std::ptr::null_mut(),
                icon_owned: false,
                icon_added: false,
                last_tip: String::new(),
            }),
        }));
        CTX.with(|c| *c.borrow_mut() = Some(ctx));

        let (icon, icon_owned) = load_tray_icon();
        ctx.ui.borrow_mut().icon = icon;
        ctx.ui.borrow_mut().icon_owned = icon_owned;

        let hwnd = match create_window() {
            Ok(h) => h,
            Err(e) => {
                if icon_owned && !icon.is_null() {
                    // SAFETY: the icon was created above for us and nothing
                    // references it (no tray icon was ever added).
                    unsafe { DestroyIcon(icon) };
                }
                return Err(e);
            }
        };
        ctx.ui.borrow_mut().hwnd = hwnd;

        let tip = tooltip_text(&ctx.supervisor.snapshot());
        if let Err(e) = add_tray_icon(hwnd, icon, &tip) {
            log_err("Shell_NotifyIconW(NIM_ADD)", &e);
            // SAFETY: hwnd was created by this thread; nothing else holds it.
            unsafe { DestroyWindow(hwnd) };
            if icon_owned && !icon.is_null() {
                // SAFETY: owned icon from CreateIconFromResourceEx, unreferenced.
                unsafe { DestroyIcon(icon) };
            }
            return Err(e);
        }
        {
            let mut ui = ctx.ui.borrow_mut();
            ui.icon_added = true;
            ui.last_tip = tip;
        }

        // SAFETY: hwnd is our valid window; id 1 is free; None callback
        // means the shell delivers WM_TIMER to the window procedure.
        if unsafe { SetTimer(hwnd, TIMER_ID, TIP_PERIOD_MS, None) } == 0 {
            // Not fatal: the tooltip simply stops refreshing.
            log_err(
                "SetTimer",
                &crate::err!(
                    "tooltip refresh disabled: {}",
                    std::io::Error::last_os_error()
                ),
            );
        }

        let mut msg = MSG::default();
        loop {
            // SAFETY: msg is a valid, aligned MSG out-slot; the NULL window
            // filter accepts every message of this thread.
            let r = unsafe { GetMessageW(&mut msg, std::ptr::null_mut(), 0, 0) };
            if r == 0 {
                break; // WM_QUIT — clean exit
            }
            if r == -1 {
                teardown(ctx);
                return Err(crate::err!(
                    "GetMessageW failed: {}",
                    std::io::Error::last_os_error()
                ));
            }
            // SAFETY: msg holds a message returned by GetMessageW.
            unsafe { TranslateMessage(&msg) };
            // SAFETY: same; routes the message to our subclassed procedure.
            unsafe { DispatchMessageW(&msg) };
        }
        teardown(ctx);
        Ok(())
    }

    /// Idempotent teardown: NIM_DELETE (if still added), kill the timer,
    /// destroy the window, free an owned icon.
    fn teardown(ctx: &'static TrayCtx) {
        let (hwnd, icon, icon_owned, was_added) = {
            let mut ui = ctx.ui.borrow_mut();
            (
                ui.hwnd,
                ui.icon,
                ui.icon_owned,
                std::mem::replace(&mut ui.icon_added, false),
            )
        };
        if was_added && !hwnd.is_null() {
            let d = nid_base(hwnd);
            // SAFETY: d is a NOTIFYICONDATAW with cbSize/hWnd/uID set (the
            // fields NIM_DELETE reads); the icon is identified by those.
            let _ = unsafe { Shell_NotifyIconW(NIM_DELETE, &d) };
        }
        if !hwnd.is_null() {
            // SAFETY: the timer and window belong to this thread; both calls
            // are safe/idempotent for handles we own.
            unsafe { KillTimer(hwnd, TIMER_ID) };
            // SAFETY: hwnd is the message-only window we created.
            unsafe { DestroyWindow(hwnd) };
        }
        if icon_owned && !icon.is_null() {
            // SAFETY: icon was created by CreateIconFromResourceEx for us
            // (a LoadIconW fallback is shared and intentionally NOT freed).
            unsafe { DestroyIcon(icon) };
        }
    }

    // ---- icon ----------------------------------------------------------------

    /// Resolve the tray HICON: parse the embedded ICO's RT_ICON entry for a
    /// 32px image and let `CreateIconFromResourceEx` build the icon;
    /// fall back to the shared application icon so the tray always works.
    /// Returns (HICON, owned-by-us).
    fn load_tray_icon() -> (HICON, bool) {
        if let Some(bytes) = ico_image_bytes(ICON_BYTES, ICON_SIZE) {
            // SAFETY: bytes points into our read-only embedded ICO data with
            // exactly the length taken from the directory entry (the RT_ICON
            // payload: BITMAPINFOHEADER + masks); 0x00030000 is the
            // documented Win32 icon-resource version; fIcon=1 means icon.
            let icon = unsafe {
                CreateIconFromResourceEx(
                    bytes.as_ptr(),
                    bytes.len() as u32,
                    1,           // TRUE: icon (not cursor)
                    0x0003_0000, // Win32 format version
                    ICON_SIZE as i32,
                    ICON_SIZE as i32,
                    LR_DEFAULTCOLOR,
                )
            };
            if !icon.is_null() {
                return (icon, true);
            }
        }
        // SAFETY: IDI_APPLICATION is a system resource id; LoadIconW returns
        // a SHARED icon (never destroyed — hence owned=false).
        (
            unsafe { LoadIconW(std::ptr::null_mut(), IDI_APPLICATION) },
            false,
        )
    }

    // ---- window ---------------------------------------------------------------

    /// Create the message-only window from the predefined STATIC class and
    /// subclass it with our procedure.
    fn create_window() -> crate::error::Result<HWND> {
        let class = to_wide("STATIC");
        let title = to_wide("MultiTunnelTray");
        // SAFETY: message-only window (HWND_MESSAGE parent) from the
        // predefined STATIC system class — no RegisterClass needed; the
        // hinstance is ignored for system classes and lpparam is unused.
        // Geometry is all zero (never shown); both wide strings are
        // NUL-terminated buffers we own.
        let hwnd = unsafe {
            CreateWindowExW(
                0,              // dwExStyle: none
                class.as_ptr(), // system "STATIC" class
                title.as_ptr(), // window name (diagnostics only)
                0,              // dwStyle: none — message-only, never shown
                0,
                0,
                0,
                0,                    // position/size: unused
                HWND_MESSAGE,         // parent: makes it message-only
                std::ptr::null_mut(), // hmenu: not a child window
                std::ptr::null_mut(), // hinstance: ignored for system classes
                std::ptr::null(),     // lpparam: no creation data
            )
        };
        if hwnd.is_null() {
            return Err(crate::err!(
                "CreateWindowExW(tray window) failed: {}",
                std::io::Error::last_os_error()
            ));
        }
        // Subclass the window: from here on, tray callbacks / WM_TIMER /
        // WM_COMMAND reach our procedure. The original STATIC procedure only
        // mattered during creation; unhandled messages go to DefWindowProcW
        // (valid for any window, including system-class ones).
        // The fn-pointer→integer cast is the documented Win32 idiom for
        // passing a procedure to GWLP_WNDPROC (via *const () as clippy
        // requires).
        let prev = unsafe {
            SetWindowLongPtrW(
                hwnd,
                GWLP_WNDPROC,
                tray_wndproc as *const () as usize as isize,
            )
        };
        if prev == 0 {
            let e = crate::err!(
                "SetWindowLongPtrW(GWLP_WNDPROC) failed: {}",
                std::io::Error::last_os_error()
            );
            // SAFETY: hwnd was created above on this thread.
            unsafe { DestroyWindow(hwnd) };
            return Err(e);
        }
        Ok(hwnd)
    }

    // ---- window procedure -------------------------------------------------------

    /// Subclass procedure installed over the STATIC window. Handles the tray
    /// callback, tooltip timer and menu commands; everything else falls to
    /// DefWindowProcW. Runs only on the message-loop thread.
    unsafe extern "system" fn tray_wndproc(
        hwnd: HWND,
        msg: u32,
        wparam: WPARAM,
        lparam: LPARAM,
    ) -> LRESULT {
        match msg {
            WM_TIMER if wparam == TIMER_ID => {
                if let Some(ctx) = ctx() {
                    on_timer(ctx, hwnd);
                }
                0
            }
            WM_DESTROY => {
                // Defensive: if the window dies for any reason, stop the
                // loop instead of pumping forever.
                // SAFETY: no preconditions — posts WM_QUIT to this thread.
                unsafe { PostQuitMessage(0) };
                0
            }
            WM_COMMAND => {
                // Menu selections arrive as LOWORD(wParam) = item id.
                if let (Some(cmd), Some(ctx)) = (cmd_from_id(wparam & 0xFFFF), ctx()) {
                    on_command(ctx, hwnd, cmd);
                }
                0
            }
            TRAY_CALLBACK => match lparam as u32 {
                // Classic NIF_MESSAGE semantics: lParam is the mouse message.
                WM_LBUTTONUP | WM_RBUTTONUP => {
                    if let Some(ctx) = ctx() {
                        show_menu(ctx, hwnd);
                    }
                    0
                }
                _ => {
                    // SAFETY: passthrough of unmatched parameters.
                    unsafe { DefWindowProcW(hwnd, msg, wparam, lparam) }
                }
            },
            _ => {
                // SAFETY: passthrough of unmatched parameters.
                unsafe { DefWindowProcW(hwnd, msg, wparam, lparam) }
            }
        }
    }

    // ---- handlers ---------------------------------------------------------------

    /// WM_TIMER: refresh the tooltip from a fresh snapshot when it changed.
    fn on_timer(ctx: &'static TrayCtx, hwnd: HWND) {
        let tip = tooltip_text(&ctx.supervisor.snapshot());
        let changed = {
            let mut ui = ctx.ui.borrow_mut();
            if ui.last_tip == tip {
                false
            } else {
                ui.last_tip = tip.clone();
                true
            }
        };
        if changed {
            let mut d = nid_base(hwnd);
            d.uFlags = NIF_TIP;
            d.szTip = tip_array(&tip);
            // SAFETY: d is a NOTIFYICONDATAW with cbSize/hWnd/uID and the
            // NIF_TIP payload set; NIM_MODIFY only reads it. A missing icon
            // (e.g. mid-Exit) just returns FALSE, which we ignore.
            let _ = unsafe { Shell_NotifyIconW(NIM_MODIFY, &d) };
        }
    }

    fn on_command(ctx: &'static TrayCtx, hwnd: HWND, cmd: Cmd) {
        match cmd {
            Cmd::Connect => spawn_supervisor_op(ctx, "connect", |sup| sup.connect()),
            Cmd::Disconnect => spawn_supervisor_op(ctx, "disconnect", |sup| sup.disconnect()),
            Cmd::ShowRawStatus => show_raw_status(ctx),
            Cmd::OpenLogFolder => open_log_folder(ctx),
            Cmd::EditConfig => edit_config(ctx),
            Cmd::Exit => exit_app(ctx, hwnd),
        }
    }

    /// Supervisor ops hold an op_lock and can block up to ~15 s — they must
    /// NEVER run inside the window procedure (it would wedge the tray), so
    /// every one of them gets a worker thread.
    fn spawn_supervisor_op(
        ctx: &'static TrayCtx,
        op: &'static str,
        f: impl FnOnce(&Supervisor) -> crate::error::Result<()> + Send + 'static,
    ) {
        let sup = ctx.supervisor.clone();
        thread::spawn(move || {
            if let Err(e) = f(&sup) {
                log_err(op, &e);
            }
        });
    }

    /// "Show raw status": dump snapshot + raw net-merge status to
    /// state_dir/net-merge-status.txt and open it in notepad.
    fn show_raw_status(ctx: &'static TrayCtx) {
        let snap = ctx.supervisor.snapshot();
        let path = status_dump_path(ctx.supervisor.state_dir());
        if let Err(e) = write_status_dump(&path, &snap) {
            log_err("write status dump", &e);
            return;
        }
        spawn_detached("notepad.exe", &path);
    }

    /// "Open log folder": ensure the dir exists (the supervisor normally
    /// creates it on connect), then open it in explorer.
    fn open_log_folder(ctx: &'static TrayCtx) {
        let dir = ctx.supervisor.log_dir();
        if let Err(e) = std::fs::create_dir_all(dir) {
            log_err("create log dir", &crate::err!("{}", e));
        }
        spawn_detached("explorer.exe", dir);
    }

    /// "Edit config": open the loaded config.json in notepad.
    fn edit_config(ctx: &'static TrayCtx) {
        spawn_detached("notepad.exe", &ctx.config_path);
    }

    /// Fire-and-forget helper process (spawn never blocks the message loop;
    /// explorer.exe exits nonzero by design, so no status check at all).
    fn spawn_detached(program: &str, arg: &Path) {
        let _ = std::process::Command::new(program).arg(arg).spawn();
    }

    /// Exit: remove the tray icon first (no ghost), best-effort disconnect
    /// on a worker bounded by [`EXIT_WAIT`], then quit the message loop.
    fn exit_app(ctx: &'static TrayCtx, hwnd: HWND) {
        let was_added = {
            let mut ui = ctx.ui.borrow_mut();
            std::mem::replace(&mut ui.icon_added, false)
        };
        if was_added {
            let d = nid_base(hwnd);
            // SAFETY: d carries the cbSize/hWnd/uID NIM_DELETE identifies
            // the icon by; deleting an already-deleted icon returns FALSE.
            let _ = unsafe { Shell_NotifyIconW(NIM_DELETE, &d) };
        }
        // Best-effort disconnect off-thread; bounded wait so a stuck
        // op_lock (up to ~15 s) cannot hold the exit hostage.
        let sup = ctx.supervisor.clone();
        let (done_tx, done_rx) = std::sync::mpsc::channel::<()>();
        thread::spawn(move || {
            let _ = sup.disconnect(); // best-effort by contract
            let _ = done_tx.send(());
        });
        let _ = done_rx.recv_timeout(EXIT_WAIT); // elapsed, done or dropped
                                                 // SAFETY: no preconditions — posts WM_QUIT to this thread's queue,
                                                 // which makes the GetMessageW loop in `run` return 0.
        unsafe { PostQuitMessage(0) };
    }

    // ---- popup menu --------------------------------------------------------------

    /// Build the menu FRESH from the current snapshot and show it at the
    /// cursor. No `ctx.ui` borrow is held across `TrackPopupMenuEx` (its
    /// modal loop re-enters this procedure with other messages).
    fn show_menu(ctx: &'static TrayCtx, hwnd: HWND) {
        let plan = menu_plan(
            &ctx.supervisor.snapshot(),
            ctx.supervisor.net_merge_enabled(),
        );
        // SAFETY: fresh popup menu owned by this thread; null only on
        // failure, which we check.
        let hmenu = unsafe { CreatePopupMenu() };
        if hmenu.is_null() {
            log_err(
                "CreatePopupMenu",
                &crate::err!("{}", std::io::Error::last_os_error()),
            );
            return;
        }
        for entry in &plan {
            append_entry(hmenu, entry);
        }
        let mut pt = POINT { x: 0, y: 0 };
        // SAFETY: pt is a writable, aligned out-slot for the cursor pos.
        let have_pos = unsafe { GetCursorPos(&mut pt) } != 0;
        if have_pos {
            // KB Q135788: the owner must be foreground before showing a
            // tray menu or it will not dismiss when the user clicks away.
            // SAFETY: hwnd is our valid window.
            unsafe { SetForegroundWindow(hwnd) };
        }
        // SAFETY: hmenu was created above and is valid; the flags are
        // documented constants; a NULL lptpm means "no exclusion rect".
        // Modal loop: safe to re-enter the procedure (see fn docs).
        let _shown = unsafe {
            TrackPopupMenuEx(
                hmenu,
                TPM_RIGHTBUTTON | TPM_BOTTOMALIGN,
                pt.x,
                pt.y,
                hwnd,
                std::ptr::null(),
            )
        };
        if have_pos {
            // SAFETY: hwnd is our window; WM_NULL is the documented
            // post-menu no-op from KB Q135788.
            unsafe { PostMessageW(hwnd, WM_NULL, 0, 0) };
        }
        // SAFETY: destroys the menu we created (it owns its items).
        unsafe { DestroyMenu(hmenu) };
    }

    /// Append one plan entry; failures are logged and the rest of the menu
    /// still renders (best-effort, like every tray shell out there).
    fn append_entry(hmenu: HMENU, entry: &MenuEntry) {
        let ok = match entry {
            MenuEntry::Separator => {
                // SAFETY: hmenu is valid; MF_SEPARATOR requires a NULL
                // lpNewItem and ignores the id.
                unsafe { AppendMenuW(hmenu, MF_SEPARATOR, 0, std::ptr::null()) }
            }
            MenuEntry::Info(label) => {
                let wide = to_wide(label);
                // SAFETY: hmenu is valid; wide is a NUL-terminated buffer we
                // own; id 0 is unused because grayed rows are unselectable.
                unsafe { AppendMenuW(hmenu, MF_STRING | MF_GRAYED, 0, wide.as_ptr()) }
            }
            MenuEntry::Item {
                label,
                cmd,
                enabled,
            } => {
                let wide = to_wide(label);
                let flags = if *enabled {
                    MF_STRING
                } else {
                    MF_STRING | MF_GRAYED
                };
                // SAFETY: hmenu is valid; wide is NUL-terminated; the id
                // maps back through cmd_from_id on WM_COMMAND.
                unsafe { AppendMenuW(hmenu, flags, id_for_cmd(*cmd), wide.as_ptr()) }
            }
        };
        if ok == 0 {
            log_err(
                "AppendMenuW",
                &crate::err!("{}", std::io::Error::last_os_error()),
            );
        }
    }

    // ---- Shell_NotifyIconW glue -------------------------------------------------

    /// NOTIFYICONDATAW skeleton with the identity fields every NIM_* call
    /// needs (cbSize/hWnd/uID). Zero-filled: an all-zero NOTIFYICONDATAW is
    /// valid (arrays are u16, the union holds u32s, the GUID zeroed).
    fn nid_base(hwnd: HWND) -> NOTIFYICONDATAW {
        NOTIFYICONDATAW {
            cbSize: std::mem::size_of::<NOTIFYICONDATAW>() as u32,
            hWnd: hwnd,
            uID: TRAY_ID,
            ..Default::default()
        }
    }

    /// NIM_ADD with message + icon + tooltip.
    fn add_tray_icon(hwnd: HWND, icon: HICON, tip: &str) -> crate::error::Result<()> {
        let mut d = nid_base(hwnd);
        d.uFlags = NIF_MESSAGE | NIF_ICON | NIF_TIP;
        d.uCallbackMessage = TRAY_CALLBACK;
        d.hIcon = icon;
        d.szTip = tip_array(tip);
        // SAFETY: d is fully initialized for NIM_ADD (identity + flags +
        // callback message + icon + NUL-terminated tip inside szTip).
        if unsafe { Shell_NotifyIconW(NIM_ADD, &d) } == 0 {
            return Err(crate::err!(
                "Shell_NotifyIconW(NIM_ADD) failed: {}",
                std::io::Error::last_os_error()
            ));
        }
        Ok(())
    }
}

